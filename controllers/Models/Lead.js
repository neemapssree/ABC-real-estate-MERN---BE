const mongoose = require('mongoose');

const LeadSchema = new mongoose.Schema({
    firstName: {
        type: String,
        required: true,
        trim: true,
    },
    lastName: {
        type: String,
        required: true,
        trim: true
    },
    email: {
        type: String,
        required: true,
        lowercase: true,
    },
    phone: {
        type: String,
        required: true,
        trim: true,
    },
    message: {
        type: String,
    }
}, { timestamps: true });

const Lead = mongoose.model('Lead', LeadSchema);
module.exports = Lead;